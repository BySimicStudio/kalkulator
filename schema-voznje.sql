-- VOŽNJE — svaki posao ima više vožnji, ne jednu
-- Pokreni u Supabase SQL editoru. Idempotentno, može više puta.
--
-- Do materijala i nazad, do CNC-a, na montažu pa opet nazad, nekad i
-- dostava komada negde usput. Neke od tih vožnji se naplaćuju klijentu,
-- neke ne — ali gorivo i habanje se troše na svakoj.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Trošak kombija — koliko te stvarno košta kilometar
-- ---------------------------------------------------------------------
alter table public.profili add column if not exists kombi_potrosnja numeric not null default 10;  -- l/100km
alter table public.profili add column if not exists cena_goriva     numeric not null default 0;   -- RSD/l
alter table public.profili add column if not exists kombi_habanje   numeric not null default 0;   -- RSD/km, gume i servis

-- ---------------------------------------------------------------------
-- projekat_voznje
-- naplata: 'ne' se ne naplaćuje, 'tarifa' po tvojim km cenama sa
-- servisnim radijusom, 'fiksno' dogovoren iznos po vožnji.
-- ---------------------------------------------------------------------
create table if not exists public.projekat_voznje (
  id            bigint generated by default as identity primary key,
  korisnik_id   uuid not null default auth.uid() references auth.users(id) on delete cascade,
  projekat_id   bigint not null references public.projekti(id) on delete cascade,
  svrha         text not null default 'ostalo',
  opis          text,
  km            numeric not null default 0,      -- u jednom smeru
  povratno      boolean not null default true,
  broj_puta     int not null default 1,
  naplata       text not null default 'tarifa',
  naplata_iznos numeric not null default 0,      -- samo za 'fiksno', po vožnji
  redosled      int not null default 0,
  napravljen    timestamptz not null default now()
);
create index if not exists projekat_voznje_projekat_idx on public.projekat_voznje (projekat_id);

alter table public.projekat_voznje drop constraint if exists projekat_voznje_naplata_check;
alter table public.projekat_voznje
  add constraint projekat_voznje_naplata_check check (naplata in ('ne', 'tarifa', 'fiksno'));

alter table public.projekat_voznje enable row level security;
drop policy if exists "projekat_voznje su moje" on public.projekat_voznje;
create policy "projekat_voznje su moje" on public.projekat_voznje
  for all using (korisnik_id = auth.uid()) with check (korisnik_id = auth.uid());
